/* ---------- LptdUI.html ---------- */
function buildUi() {
  const data = read(SRC.lptdData);
  const ui = read(SRC.lptdUi);
  return `<!-- AUTO-GENERATED by op/tools/build-standalone-gas.js — KHÔNG SỬA TAY.
     Sinh lúc: ${STAMP}
     Gồm: op/app/lptd-data.js + op/app/lptd-ui.js + auto-open.
     Dữ liệu 160 unit lấy từ server qua google.script.run (getLptdBootstrap). -->
<script>
${safeJs(data)}
</script>
<script>
${safeJs(ui)}
</script>
<script>
(function () {
  'use strict';
  var tries = 0;
  function start() {
    if (window.LPTD_UI && typeof window.LPTD_UI.open === 'function') {
      window.LPTD_UI.open();
      return;
    }
    tries++;
    if (tries > 120) {
      var host = document.getElementById('modeBody');
      if (host) {
        host.innerHTML = '<section class="card lptd-loading"><div class="lptd-loading-icon">⚠️</div>' +
          '<b>Không khởi động được module LPTD</b>' +
          '<span class="lptd-muted">Kiểm tra Console (F12) hoặc tải lại trang.</span></section>';
      }
      return;
    }
    setTimeout(start, 50);
  }
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', start);
  } else {
    start();
  }
})();
</script>
`;
}

/* ---------- Main ---------- */
function main() {
  console.log('== build-standalone-gas ==');
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const files = {
    'Index.html': buildIndex(),
    'Styles.html': buildStyles(),
    'LptdUI.html': buildUi(),
    'LptdData.gs': read(SRC.lptdDataGs),
  };

  Object.keys(files).forEach(function (name) {
    const out = path.join(OUT_DIR, name);
    fs.writeFileSync(out, files[name], 'utf8');
    console.log('  ✓ ' + name + '  (' + (Buffer.byteLength(files[name], 'utf8') / 1024).toFixed(1) + ' KB)');
  });

  /* Cảnh báo nếu file viết tay còn thiếu. */
  ['Code.gs', 'appsscript.json'].forEach(function (name) {
    const p = path.join(OUT_DIR, name);
    console.log((fs.existsSync(p) ? '  • ' : '  ! THIẾU ') + name);
  });

  console.log('✓ Hoàn tất → op/gas-standalone/');
}

main();
