#!/usr/bin/env node
/* =========================================================
   op/tools/build-standalone-gas.js
   Sinh bộ file cho GAS app ĐỘC LẬP "LPTD 1–4" trong
   op/gas-standalone/ — không dùng core.js, không dùng dữ liệu
   Hackers / ETS.

   Sinh:
     op/gas-standalone/Index.html    (shell + include)
     op/gas-standalone/Styles.html   (core.css + lptd-ui.css + override)
     op/gas-standalone/LptdUI.html   (lptd-data.js + lptd-ui.js + auto-open)
     op/gas-standalone/LptdData.gs   (copy từ op/app/LptdData.gs)

   File viết tay (KHÔNG bị ghi đè):
     op/gas-standalone/Code.gs
     op/gas-standalone/appsscript.json

   Chạy:
     node op/tools/build-standalone-gas.js
   ========================================================= */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const OP = path.resolve(__dirname, '..');
const OUT_DIR = path.join(OP, 'gas-standalone');

const SRC = {
  coreCss: path.join(ROOT, 'app', 'core.css'),
  lptdCss: path.join(OP, 'app', 'lptd-ui.css'),
  lptdData: path.join(OP, 'app', 'lptd-data.js'),
  lptdUi: path.join(OP, 'app', 'lptd-ui.js'),
  lptdDataGs: path.join(OP, 'app', 'LptdData.gs'),
};

function read(p) {
  if (!fs.existsSync(p)) throw new Error('Thiếu file: ' + p);
  return fs.readFileSync(p, 'utf8');
}

function safeJs(src) {
  return src.replace(/<\/script/gi, '<\\/script');
}
function safeCss(src) {
  return src.replace(/<\/style/gi, '<\\/style');
}

const STAMP = new Date().toISOString();

/* ---------- Index.html ---------- */
function buildIndex() {
  return `<!DOCTYPE html>
<html lang="vi">
<head>
  <base target="_top">
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>LPTD 1–4 — Dictation &amp; Shadowing</title>
  <?!= include('Styles'); ?>
</head>
<body>
<div class="app-shell">
  <main class="main">
    <header class="main-header">
      <div class="logo-icon">🎧</div>
      <div style="flex:1;min-width:0">
        <div class="header-title" id="headerTitle">LPTD 1–4</div>
        <div class="header-sub" id="headerSub">Listening Practice Through Dictation</div>
      </div>
      <div class="header-right">
        <button type="button" class="btn btn-outline btn-sm" id="btnTheme" title="Sáng / Tối" aria-label="Đổi giao diện sáng tối">🌙</button>
      </div>
    </header>

    <div class="main-body">
      <div class="container">

        <div class="hero">
          <div class="hero-row">
            <div>
              <h1 id="heroTitle">Listening Practice Through Dictation</h1>
              <p id="heroSub">LPTD 1–4 · 160 unit · Nghe – chép chính tả – shadowing</p>
            </div>
            <span class="badge accent" id="heroStatus">⏳ Đang tải</span>
          </div>
          <div class="hero-badges">
            <span class="badge" id="heroDictationBadge">📝 Dictation</span>
            <span class="badge" id="heroShadowingBadge">🗣️ Shadowing</span>
            <span class="badge" id="heroBadgeCount">🎧 160 unit · 4 cuốn</span>
          </div>
        </div>

        <div id="modeBody">
          <section class="card lptd-loading">
            <div class="lptd-loading-icon">🎧</div>
            <b>Đang tải dữ liệu LPTD…</b>
            <span class="lptd-muted">160 unit · 4 cuốn · audio phát trực tiếp từ CDN</span>
          </section>
        </div>

      </div>
    </div>
  </main>
</div>

<?!= include('LptdUI'); ?>
<script>
(function () {
  'use strict';
  /* Theme sáng/tối — độc lập, chỉ lưu localStorage trình duyệt. */
  var KEY = 'toeic_lptd_theme';
  var btn = document.getElementById('btnTheme');
  function apply(theme) {
    if (theme === 'dark') document.documentElement.setAttribute('data-theme', 'dark');
    else document.documentElement.removeAttribute('data-theme');
    if (btn) btn.textContent = theme === 'dark' ? '☀️' : '🌙';
  }
  var saved = null;
  try { saved = localStorage.getItem(KEY); } catch (e) {}
  apply(saved === 'dark' ? 'dark' : 'light');
  if (btn) {
    btn.addEventListener('click', function () {
      var next = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
      apply(next);
      try { localStorage.setItem(KEY, next); } catch (e) {}
    });
  }
})();
</script>
</body>
</html>
`;
}

/* ---------- Styles.html ---------- */
