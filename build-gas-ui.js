#!/usr/bin/env node
/* =========================================================
   op/tools/build-gas-ui.js
   Sinh op/app/LptdUI.html để dán/include vào Google Apps Script.

   Nội dung gồm:
     - <style>  : op/app/lptd-ui.css
     - <script> : op/app/lptd-data.js  (catalog + URL builder)
     - <script> : op/app/lptd-ui.js    (module UI)

   Chạy:
     node op/tools/build-gas-ui.js
   ========================================================= */
'use strict';

const fs = require('fs');
const path = require('path');

const OP = path.resolve(__dirname, '..');
const FILES = {
  css: path.join(OP, 'app', 'lptd-ui.css'),
  data: path.join(OP, 'app', 'lptd-data.js'),
  ui: path.join(OP, 'app', 'lptd-ui.js'),
};
const OUT = path.join(OP, 'app', 'LptdUI.html');

function read(p) {
  if (!fs.existsSync(p)) throw new Error('Thiếu file: ' + p);
  return fs.readFileSync(p, 'utf8');
}

function safeJs(src) {
  return src.replace(/<\/script/gi, '<\\/script');
}
function safeCss(src) {
  return src.replace(/<\/style/gi, '<\\/style');
}

function main() {
  console.log('== build-gas-ui ==');
  const css = read(FILES.css);
  const data = read(FILES.data);
  const ui = read(FILES.ui);
  const stamp = new Date().toISOString();

  const html = [
    '<!-- =========================================================',
    '     AUTO-GENERATED by op/tools/build-gas-ui.js — KHÔNG SỬA TAY.',
    '     Sinh lúc: ' + stamp,
    '     Gồm: lptd-data.js + lptd-ui.css + lptd-ui.js',
    '     Cách dùng: dán file này vào GAS với tên "LptdUI.html",',
    '     sau đó thêm <?!= include(\'LptdUI\'); ?> vào Index.html.',
    '     ========================================================= -->',
    '<style>',
    safeCss(css),
    '</style>',
    '',
    '<script>',
    safeJs(data),
    '</script>',
    '',
    '<script>',
    safeJs(ui),
    '</script>',
    '',
  ].join('\n');

  fs.writeFileSync(OUT, html, 'utf8');
  const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
  console.log('  ✓ ' + path.relative(OP, OUT) + '  (' + kb + ' KB)');
  console.log('    - CSS : ' + (css.length / 1024).toFixed(1) + ' KB');
  console.log('    - Data: ' + (data.length / 1024).toFixed(1) + ' KB');
  console.log('    - UI  : ' + (ui.length / 1024).toFixed(1) + ' KB');
  console.log('✓ Hoàn tất.');
}

main();
